#include "libft.h"

void	ft_putnbr_fd(int n, int fd)
{
	int	out;

	if (n == -2147483648)
	{
		write(fd, "-2147483648", 11);
		return ;
	}
	if (n < 0)
	{
		write(fd, "-", 1);
		n = n * (-1);
	}
	out = (n % 10) + '0';
	if (n >= 10)
	{
		n = n / 10;
		ft_putnbr_fd(n, fd);
	}
	write(fd, &out, 1);
}
